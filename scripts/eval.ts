import { readFile, writeFile } from 'node:fs/promises';
import { parse as parseYaml } from 'yaml';
import { createPromptRegistry } from '../src/prompts/registry.ts';
import { countTokensFor } from '../src/providers/openai.ts';
import { priceFor } from '../src/accounting/pricing.ts';

/**
 * Compares template versions on what they cost to send.
 *
 * What this deliberately does not do is score answer quality. Doing that needs
 * a real provider and a judgement about what a good summary is, and a runner
 * that produced quality scores from a mock would be inventing them. What it can
 * measure without a key is exact, reproducible and still the thing most often
 * left unexamined: a longer prompt is paid for on every single call, and the
 * v2 template is materially longer than v1.
 *
 * With a provider configured, the same case list is what a scored evaluation
 * would run against — the cases are the reusable part.
 */
interface Case {
  name: string;
  variables: Record<string, unknown>;
}

interface Row {
  template: string;
  caseName: string;
  promptTokens: number;
}

const MODEL = 'gpt-4o-mini';
const REPORT = new URL('../docs/eval-report.md', import.meta.url);

function table(rows: string[][]): string {
  const widths =
    rows[0]?.map((_, i) => Math.max(...rows.map((row) => (row[i] ?? '').length))) ?? [];
  const render = (row: string[]) =>
    `| ${row.map((cell, i) => cell.padEnd(widths[i] ?? 0)).join(' | ')} |`;
  const divider = `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`;
  return [render(rows[0] ?? []), divider, ...rows.slice(1).map(render)].join('\n');
}

async function buildReport(): Promise<string> {
  const raw = await readFile(new URL('../eval/cases.yaml', import.meta.url), 'utf8');
  const { cases } = parseYaml(raw) as { cases: Case[] };
  const registry = createPromptRegistry();

  const versions = registry
    .list()
    .map((entry) => entry.id)
    .filter((id) => id.startsWith('summarize@'))
    .sort();

  const rows: Row[] = [];
  for (const template of versions) {
    for (const testCase of cases) {
      const rendered = registry.render(template, testCase.variables);
      if (!rendered.ok) throw new Error(`${template} / ${testCase.name}: ${rendered.error}`);
      rows.push({
        template,
        caseName: testCase.name,
        promptTokens: countTokensFor(rendered.prompt, MODEL),
      });
    }
  }

  const price = priceFor(MODEL);
  const perVersion = versions.map((template) => {
    const own = rows.filter((row) => row.template === template);
    const total = own.reduce((sum, row) => sum + row.promptTokens, 0);
    const mean = Math.round(total / own.length);
    const perThousandCalls = price ? (mean / 1_000_000) * price.inputPerMillion * 1000 : null;
    return { template, mean, perThousandCalls };
  });

  const baseline = perVersion[0];
  const lines: string[] = [
    '# Prompt evaluation',
    '',
    '<!-- Generated by `npm run eval`. CI fails if this file and the templates',
    '     have drifted apart; edit the templates or the cases, not this file. -->',
    '',
    `Every version of the \`summarize\` template rendered against every case in`,
    '`eval/cases.yaml`, measured with the same tokenizer the API bills against.',
    '',
    '## Prompt tokens per case',
    '',
    table([
      ['case', ...versions],
      ...[...new Set(rows.map((row) => row.caseName))].map((caseName) => [
        caseName,
        ...versions.map((template) =>
          String(
            rows.find((row) => row.template === template && row.caseName === caseName)
              ?.promptTokens ?? 0,
          ),
        ),
      ]),
    ]),
    '',
    '## Cost of the prompt itself',
    '',
    `Mean prompt tokens per call, and what that costs to send a thousand times at`,
    `\`${MODEL}\` input pricing (${price?.asOf ?? 'unknown'} snapshot).`,
    '',
    table([
      ['template', 'mean prompt tokens', 'per 1,000 calls', 'vs first version'],
      ...perVersion.map((entry) => [
        entry.template,
        String(entry.mean),
        entry.perThousandCalls === null ? 'unpriced' : `$${entry.perThousandCalls.toFixed(4)}`,
        baseline && entry.mean !== baseline.mean
          ? `${entry.mean > baseline.mean ? '+' : ''}${String(
              Math.round(((entry.mean - baseline.mean) / baseline.mean) * 100),
            )}%`
          : '—',
      ]),
    ]),
    '',
    '## What this does not measure',
    '',
    'Answer quality. Scoring that needs a real provider and a defensible view of',
    'what a good summary is; a number produced from the mock provider would be',
    'invented. What is measured here is exact and is paid on every call — the',
    'instruction block that makes v2 more specific is also charged for every',
    'time it is sent, and this is the number to weigh that against.',
    '',
    'The completion side is not included because it depends on the answer, not on',
    'the template.',
    '',
  ];

  return lines.join('\n');
}

async function main(): Promise<number> {
  const report = await buildReport();

  if (process.argv.includes('--check')) {
    const existing = await readFile(REPORT, 'utf8').catch(() => '');
    if (existing === report) {
      console.log('docs/eval-report.md is up to date');
      return 0;
    }
    console.error('docs/eval-report.md is stale — run `npm run eval` and commit the result');
    return 1;
  }

  await writeFile(REPORT, report);
  console.log('wrote docs/eval-report.md');
  return 0;
}

process.exitCode = await main();
